/// Cursor over an args buffer; the macro-emitted wasm entry shim drives
/// this in declaration order.
#[derive(Debug)]
pub struct ArgReader<'a> {
    cursor: &'a [u8],
}

impl<'a> ArgReader<'a> {
    /// Wrap a borrowed buffer.
    pub fn new(buf: &'a [u8]) -> Self {
        Self { cursor: buf }
    }

    /// Bytes not yet consumed.
    pub fn remaining(&self) -> usize {
        self.cursor.len()
    }

    /// Borrow the still-pending slice (used in tests and for adapters
    /// that need to forward bytes verbatim).
    pub fn as_slice(&self) -> &'a [u8] {
        self.cursor
    }

    fn take(&mut self, n: usize) -> Result<&'a [u8], AbiError> {
        if self.cursor.len() < n {
            return Err(AbiError::UnexpectedEof {
                needed: n,
                available: self.cursor.len(),
            });
        }
        let (head, tail) = self.cursor.split_at(n);
        self.cursor = tail;
        Ok(head)
    }

    /// Read a single byte.
    pub fn read_u8(&mut self) -> Result<u8, AbiError> {
        let bytes = self.take(1)?;
        Ok(bytes[0])
    }

    /// Read a big-endian `u16`.
    pub fn read_u16(&mut self) -> Result<u16, AbiError> {
        let bytes = self.take(2)?;
        let mut a = [0u8; 2];
        a.copy_from_slice(bytes);
        Ok(u16::from_be_bytes(a))
    }

    /// Read a big-endian `u32`.
    pub fn read_u32(&mut self) -> Result<u32, AbiError> {
        let bytes = self.take(4)?;
        let mut a = [0u8; 4];
        a.copy_from_slice(bytes);
        Ok(u32::from_be_bytes(a))
    }

    /// Read a big-endian `u64`.
    pub fn read_u64(&mut self) -> Result<u64, AbiError> {
        let bytes = self.take(8)?;
        let mut a = [0u8; 8];
        a.copy_from_slice(bytes);
        Ok(u64::from_be_bytes(a))
    }

    /// Read a big-endian `u128`.
    pub fn read_u128(&mut self) -> Result<u128, AbiError> {
        let bytes = self.take(16)?;
        let mut a = [0u8; 16];
        a.copy_from_slice(bytes);
        Ok(u128::from_be_bytes(a))
    }

    /// Read a 32-byte address payload (post-quantum address, hash, raw
    /// pubkey hash, etc.).
    pub fn read_address(&mut self) -> Result<[u8; 32], AbiError> {
        let bytes = self.take(32)?;
        let mut a = [0u8; 32];
        a.copy_from_slice(bytes);
        Ok(a)
    }

    /// Read a 32-byte `ObjectId`.
    pub fn read_object_id(&mut self) -> Result<ObjectId, AbiError> {
        Ok(ObjectId(self.read_address()?))
    }

    /// Read a `RuntimeHandle` (4-byte BE i32). Sentinel `-1` is rejected
    /// because a valid arg handle must point at a real borrow.
    pub fn read_handle(&mut self) -> Result<RuntimeHandle, AbiError> {
        let bytes = self.take(4)?;
        let mut a = [0u8; 4];
        a.copy_from_slice(bytes);
        let raw = i32::from_be_bytes(a);
        if raw < 0 {
            return Err(AbiError::InvalidHandle(raw));
        }
        Ok(RuntimeHandle::from_raw(raw))
    }

    /// Decode a recursive `TypeTag` using its canonical codec.
    ///
    /// The encoded `TypeTag` is *not* length-prefixed — the codec is
    /// self-delimiting. To decode within a larger buffer we walk the
    /// codec via `TypeTag::decode_from`, then advance our cursor by
    /// however many bytes it consumed.
    pub fn read_type_tag(&mut self) -> Result<TypeTag, AbiError> {
        let before = self.cursor;
        let mut walker = before;
        let tag = TypeTag::decode_from(&mut walker, 0)?;
        let consumed = before.len() - walker.len();
        // Advance our own cursor by the exact number of bytes the
        // TypeTag codec consumed.
        self.cursor = &self.cursor[consumed..];
        Ok(tag)
    }

    /// Read a length-prefixed byte vector.
    pub fn read_bytes(&mut self) -> Result<Vec<u8>, AbiError> {
        let len = self.read_u32()? as usize;
        let bytes = self.take(len)?;
        Ok(bytes.to_vec())
    }

    /// Read a length-prefixed UTF-8 string.
    pub fn read_string(&mut self) -> Result<String, AbiError> {
        let len = self.read_u32()? as usize;
        let bytes = self.take(len)?;
        core::str::from_utf8(bytes)
            .map(|s| s.to_owned())
            .map_err(|_| AbiError::InvalidUtf8)
    }

    /// Read a 1-byte boolean. Strict: only `0` and `1` are accepted.
    pub fn read_bool(&mut self) -> Result<bool, AbiError> {
        let b = self.read_u8()?;
        match b {
            0 => Ok(false),
            1 => Ok(true),
            other => Err(AbiError::InvalidBool(other)),
        }
    }

    /// Assert that the buffer has been fully consumed; called by the
    /// macro-emitted entry shim before dispatching to the user fn.
    pub fn expect_eof(&self) -> Result<(), AbiError> {
        if self.cursor.is_empty() {
            Ok(())
        } else {
            Err(AbiError::TrailingBytes {
                remaining: self.cursor.len(),
            })
        }
    }
}

