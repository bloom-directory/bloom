contract! {
    contract Erc20 {
        storage {
            name:          Bytes32;
            symbol:        Bytes32;
            decimals:      u64;

            total_supply:  U256                              @ "erc20.total_supply";
            balances:      Mapping<Address, U256>            @ "erc20.balance:";
            allowances:    Mapping<(Address, Address), U256> @ "erc20.allowance:";
        }

        event Transfer(#[indexed] from: Address, #[indexed] to: Address, value: U256);
        event Approval(#[indexed] owner: Address, #[indexed] spender: Address, value: U256);

        fn total_supply() -> U256;
        fn balance_of(owner: Address) -> U256;
        fn allowance(owner: Address, spender: Address) -> U256;
        fn transfer(to: Address, amount: U256) -> bool;
        fn transfer_from(from: Address, to: Address, amount: U256) -> bool;
        fn approve(spender: Address, value: U256) -> bool;
        fn name() -> Bytes32;
        fn symbol() -> Bytes32;
    }
}

// ---------------------------------------------------------------------------
// U256::MAX sentinel for unlimited allowance
// ---------------------------------------------------------------------------

const U256_MAX: U256 = U256([0xff; 32]);

// ---------------------------------------------------------------------------
// Mint helper (used by init)
// ---------------------------------------------------------------------------

/// Increase the balance of `to` by `amount` and update total supply.
/// Emits Transfer(0x0, to, amount).
fn mint(to: &[u8; 32], amount: U256) {
    if amount.is_zero() {
        return;
    }
    // Update balance.
    let prev = erc20::abi::storage::balances::get(to);
    let next = prev
        .checked_add(amount)
        .unwrap_or_else(|| petal::revert("erc20: mint overflow"));
    erc20::abi::storage::balances::set(to, &next);

    // Update total supply.
    let ts = erc20::abi::storage::total_supply();
    let ts_next = ts
        .checked_add(amount)
        .unwrap_or_else(|| petal::revert("erc20: total supply overflow"));
    erc20::abi::storage::set_total_supply(&ts_next);

    // Emit Transfer(0x0, to, amount).
    let zero = [0u8; 32];
    erc20::abi::events::emit_transfer(&zero, to, &amount);
}

// ---------------------------------------------------------------------------
// Internal transfer (no event — callers emit events)
// ---------------------------------------------------------------------------

/// Debit `amount` from `from` and credit to `to`. Returns the error message
/// on insufficient balance / overflow so the caller can surface it through
/// the `Handler::Err` channel.
fn do_transfer(from: &[u8; 32], to: &[u8; 32], amount: U256) -> Result<(), &'static str> {
    if amount.is_zero() {
        // Zero transfers are allowed; nothing to do.
        return Ok(());
    }
    let from_bal = erc20::abi::storage::balances::get(from);
    let new_from = from_bal
        .checked_sub(amount)
        .ok_or("erc20: insufficient balance")?;
    erc20::abi::storage::balances::set(from, &new_from);

    let to_bal = erc20::abi::storage::balances::get(to);
    let new_to = to_bal
        .checked_add(amount)
        .ok_or("erc20: balance overflow")?;
    erc20::abi::storage::balances::set(to, &new_to);
    Ok(())
}

// ---------------------------------------------------------------------------
// Init payload parser helpers
// ---------------------------------------------------------------------------

/// Parse a `u16-BE length || bytes` field from a raw slice, returning the
/// field bytes and the remaining slice. Reverts if the slice is too short.
fn parse_length_prefixed<'a>(data: &'a [u8]) -> (&'a [u8], &'a [u8]) {
    if data.len() < 2 {
        petal::revert("erc20: init payload truncated at length prefix");
    }
    let len = u16::from_be_bytes([data[0], data[1]]) as usize;
    let rest = &data[2..];
    if rest.len() < len {
        petal::revert("erc20: init payload truncated in field bytes");
    }
    (&rest[..len], &rest[len..])
}

/// Write a string of up to 32 bytes into a `bytes32` slot (left-zero-padded,
/// i.e. ASCII occupies the right portion). Reverts if the string exceeds 32 bytes.
fn str_to_bytes32(s: &[u8]) -> [u8; 32] {
    if s.len() > 32 {
        petal::revert("erc20: name/symbol too long (max 32 bytes)");
    }
    let mut slot = [0u8; 32];
    // Right-align: put string at the end of the slot.
    let offset = 32 - s.len();
    slot[offset..].copy_from_slice(s);
    slot
}

// ---------------------------------------------------------------------------
// petal entry points (init + call wired into the macro-generated codec)
// ---------------------------------------------------------------------------

bloom_petal_sdk::petal! {
    init => do_init,
    call => do_call,
}

/// `init` — runs once at deploy time.
///
/// Payload: `name_len (u16 BE) | name | symbol_len (u16 BE) | symbol |
///           decimals (u8) | initial_supply (u256 BE, 32 B) | initial_holder (Address, 32 B)`
///
/// Kept hand-rolled because the payload is variable-length (length-prefixed
/// strings) and contains a `u8` — neither of which the chain-ABI
/// `contract!` macro can model today.
fn do_init(calldata: Vec<u8>) {
    let data = calldata.as_slice();

    // Parse name.
    let (name_bytes, rest) = parse_length_prefixed(data);
    let name_slot = str_to_bytes32(name_bytes);

    // Parse symbol.
    let (symbol_bytes, rest) = parse_length_prefixed(rest);
    let symbol_slot = str_to_bytes32(symbol_bytes);

    // Parse decimals (1 byte).
    if rest.is_empty() {
        petal::revert("erc20: init payload truncated at decimals");
    }
    let decimals = rest[0];
    let rest = &rest[1..];

    // Parse initial_supply (32 bytes, u256 BE).
    if rest.len() < 32 {
        petal::revert("erc20: init payload truncated at initial_supply");
    }
    let mut supply_bytes = [0u8; 32];
    supply_bytes.copy_from_slice(&rest[..32]);
    let initial_supply = U256(supply_bytes);
    let rest = &rest[32..];

    // Parse initial_holder (32 bytes, Address).
    if rest.len() < 32 {
        petal::revert("erc20: init payload truncated at initial_holder");
    }
    let mut holder = [0u8; 32];
    holder.copy_from_slice(&rest[..32]);
    let rest = &rest[32..];

    // No trailing bytes allowed.
    if !rest.is_empty() {
        petal::revert("erc20: init payload has trailing bytes");
    }

    // Write metadata to storage.
    erc20::abi::storage::set_name(&name_slot);
    erc20::abi::storage::set_symbol(&symbol_slot);

    // Decimals: u8 widened to u64 — the macro's u64 setter writes the value
    // big-endian into `slot[24..32]`, so the low byte (slot[31]) is the same
    // as the pre-migration `slot[31] = decimals` hand-rolled write for any
    // decimals value that fits in u8.
    erc20::abi::storage::set_decimals(decimals as u64);

    // Mint initial supply to holder (also sets total_supply).
    mint(&holder, initial_supply);
}

/// Selector for `erc20.decimals()`. Hand-dispatched because the macro's
/// typed return system cannot model a 1-byte `u8` return today. Computed at
/// runtime from the canonical signature via `bloom_chain_abi::selector`, so
/// the hashing rule stays anchored to the same source-of-truth the macro
/// uses (no hand-rolled constant).
fn sel_decimals() -> [u8; 4] {
    bloom_chain_abi::selector("erc20.decimals()")
}

/// `call` — dispatches on the 4-byte selector.
fn do_call(calldata: Vec<u8>) -> i32 {
    if calldata.len() < 4 {
        petal::revert("erc20: calldata too short");
    }
    let sel: [u8; 4] = [calldata[0], calldata[1], calldata[2], calldata[3]];

    // Hand-dispatch decimals() (1-byte return, not modelable by the macro).
    if sel == sel_decimals() {
        if calldata.len() != 4 {
            petal::revert("erc20: decimals: trailing calldata bytes");
        }
        // Storage slot was written from a u8 → u64 widening, so the low byte
        // is identical to the legacy single-byte write.
        let d = erc20::abi::storage::decimals() as u8;
        petal::return_data(&[d]);
    }

    let mut handler = Erc20Handler;
    let caller = msg::sender();
    match erc20::dispatch(&mut handler, &caller, &calldata) {
        Ok(data) => petal::return_data(&data),
        Err(DispatchError::ShortCalldata) => petal::revert("erc20: calldata too short"),
        Err(DispatchError::UnknownSelector(_)) => petal::revert("erc20: unknown selector"),
        Err(DispatchError::Decode(_)) => petal::revert("erc20: bad args"),
        Err(DispatchError::Unauthorized) => petal::revert("erc20: unauthorized"),
        Err(DispatchError::Handler(msg)) => petal::revert(msg),
    }
}

// ---------------------------------------------------------------------------
// Handler — pure business logic against the chain-owned ABI shape
// ---------------------------------------------------------------------------

struct Erc20Handler;

impl erc20::Handler for Erc20Handler {
    fn total_supply(&mut self) -> Result<U256, &'static str> {
        Ok(erc20::abi::storage::total_supply())
    }

    fn balance_of(&mut self, owner: [u8; 32]) -> Result<U256, &'static str> {
        Ok(erc20::abi::storage::balances::get(&owner))
    }

    fn allowance(
        &mut self,
        owner: [u8; 32],
        spender: [u8; 32],
    ) -> Result<U256, &'static str> {
        Ok(erc20::abi::storage::allowances::get((&owner, &spender)))
    }

    fn transfer(&mut self, to: [u8; 32], amount: U256) -> Result<bool, &'static str> {
        let sender = msg::sender();
        do_transfer(&sender, &to, amount)?;

        // Emit Transfer(sender, to, amount).
        erc20::abi::events::emit_transfer(&sender, &to, &amount);
        Ok(true)
    }

    fn transfer_from(
        &mut self,
        from: [u8; 32],
        to: [u8; 32],
        amount: U256,
    ) -> Result<bool, &'static str> {
        let caller = msg::sender();

        // Check and deduct allowance (u256::MAX means unlimited).
        let current_allow = erc20::abi::storage::allowances::get((&from, &caller));
        if current_allow != U256_MAX {
            let new_allow = current_allow
                .checked_sub(amount)
                .ok_or("erc20: insufficient allowance")?;
            erc20::abi::storage::allowances::set((&from, &caller), &new_allow);
        }

        do_transfer(&from, &to, amount)?;

        // Emit Transfer(from, to, amount).
        erc20::abi::events::emit_transfer(&from, &to, &amount);
        Ok(true)
    }

    fn approve(&mut self, spender: [u8; 32], value: U256) -> Result<bool, &'static str> {
        let owner = msg::sender();
        erc20::abi::storage::allowances::set((&owner, &spender), &value);

        // Emit Approval(owner, spender, value).
        erc20::abi::events::emit_approval(&owner, &spender, &value);
        Ok(true)
    }

    fn name(&mut self) -> Result<[u8; 32], &'static str> {
        Ok(erc20::abi::storage::name())
    }

    fn symbol(&mut self) -> Result<[u8; 32], &'static str> {
        Ok(erc20::abi::storage::symbol())
    }
}

