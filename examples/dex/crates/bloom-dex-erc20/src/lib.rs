//! bloom-dex-erc20 — ERC-20 fungible token as a bloom-chain petal.
//!
//! # Storage layout (declared via `storage { ... }` in `contract!` below)
//!
//! All keys are 32-byte BLAKE3 digests; their domain tags are chosen to be
//! collision-free with the pair AMM keys.
//!
//! | Field          | Domain tag                            | Value type           |
//! |----------------|---------------------------------------|----------------------|
//! | `name`         | `"erc20.name"`                        | Bytes32 (NUL-padded) |
//! | `symbol`       | `"erc20.symbol"`                      | Bytes32 (NUL-padded) |
//! | `decimals`     | `"erc20.decimals"`                    | u64 (low byte = u8)  |
//! | `total_supply` | `"erc20.total_supply"`                | U256                 |
//! | `balances`     | `"erc20.balance:" \|\| addr`          | U256                 |
//! | `allowances`   | `"erc20.allowance:" \|\| owner \|\| s`| U256                 |
//!
//! The ERC-20 key namespace (`erc20.*`) is intentionally shared with the
//! bloom-dex-pair petal's LP-token surface (spec §6.1). Pair declares the same
//! `total_supply`/`balances`/`allowances` tags via the same `@ "erc20.*"`
//! overrides so the two petals can read each other's state without re-encoding.
//!
//! # Init payload (chain spec §7.8 / DEX spec §6.1)
//!
//! ```text
//! name_len   : u16 BE
//! name_bytes : [u8; name_len]   (ASCII, ≤ 32 bytes)
//! symbol_len : u16 BE
//! symbol_bytes: [u8; symbol_len] (ASCII, ≤ 32 bytes)
//! decimals   : u8
//! initial_supply : [u8; 32]     (u256 BE)
//! initial_holder : [u8; 32]     (Address)
//! ```
//!
//! The init payload uses variable-length, length-prefixed string fields and a
//! `u8` for decimals — none of which are expressible in the chain-ABI
//! `contract!` macro's fixed-width type system. We therefore keep `do_init`
//! hand-rolled and only model the runtime-dispatched calls (whose args ARE
//! fixed-width) through the macro.
//!
//! # ABI
//!
//! All runtime method selectors, calldata encoding, return packing, storage
//! accessors, event emitters, and the dispatcher are generated by the chain-
//! owned `bloom_chain_abi::contract!` macro below. Method signatures
//! (canonical strings used for selector hashing) match the DEX v0 spec §4.1
//! byte-for-byte.
//!
//! `erc20.decimals()` returns a single `u8` byte, which the macro's typed
//! return system does not currently model (smallest macro int is `u64`). We
//! hand-dispatch that one selector before falling through to the macro's
//! `erc20::dispatch(...)`. The selector is computed from the canonical
//! signature string via `bloom_chain_abi::selector` so it remains anchored
//! to the same hashing rule the macro uses.

#![no_std]

extern crate alloc;

