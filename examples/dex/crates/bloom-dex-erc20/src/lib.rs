    // The macro-generated storage accessors derive slot keys from the
    // declared field tags. These asserts lock the storage layout: a slot
    // tag rename in the `contract!` block would change the on-disk key and
    // break upgrade compatibility. We compare against blake3 of the
    // explicit byte string the pre-migration erc20 used.
    // ---------------------------------------------------------------------------

    #[test]
    fn storage_slot_parity_scalars() {
        use bloom_chain_abi::storage::slot_scalar;

        // Auto-derived tags: "erc20.<field>" (default for scalar fields in
        // contract `Erc20`).
        let exp = blake3::hash(b"erc20.name");
        assert_eq!(&slot_scalar("erc20.name")[..], &exp.as_bytes()[..]);

        let exp = blake3::hash(b"erc20.symbol");
        assert_eq!(&slot_scalar("erc20.symbol")[..], &exp.as_bytes()[..]);

        let exp = blake3::hash(b"erc20.decimals");
        assert_eq!(&slot_scalar("erc20.decimals")[..], &exp.as_bytes()[..]);

        // Shared "erc20.total_supply" namespace with bloom-dex-pair (explicit
        // `@ "erc20.total_supply"` override on the `total_supply` field).
        let exp = blake3::hash(b"erc20.total_supply");
        assert_eq!(&slot_scalar("erc20.total_supply")[..], &exp.as_bytes()[..]);
    }

    #[test]
    fn storage_slot_parity_mappings() {
        use bloom_chain_abi::storage::slot_mapping;

        let addr = [0x42u8; 32];

        // Pre-migration: blake3("erc20.balance:" || addr).
        let mut buf = alloc::vec::Vec::<u8>::new();
        buf.extend_from_slice(b"erc20.balance:");
        buf.extend_from_slice(&addr);
        let exp = blake3::hash(&buf);
        assert_eq!(&slot_mapping("erc20.balance:", &addr)[..], &exp.as_bytes()[..]);

        // Pre-migration: blake3("erc20.allowance:" || owner || spender).
        let owner = [0x11u8; 32];
        let spender = [0x22u8; 32];
        let mut buf = alloc::vec::Vec::<u8>::new();
        buf.extend_from_slice(b"erc20.allowance:");
        buf.extend_from_slice(&owner);
        buf.extend_from_slice(&spender);
        let exp = blake3::hash(&buf);

        let mut concat = [0u8; 64];
        concat[..32].copy_from_slice(&owner);
        concat[32..].copy_from_slice(&spender);
        assert_eq!(
            &slot_mapping("erc20.allowance:", &concat)[..],
            &exp.as_bytes()[..]
        );
    }
