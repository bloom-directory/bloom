// ---------------------------------------------------------------------------
// Storage key derivation
// ---------------------------------------------------------------------------

/// Storage key for the pair petal hash: `blake3("factory.pair_petal_hash")`.
fn k_pair_hash() -> [u8; 32] {
    crypto::blake3(b"factory.pair_petal_hash")
}

/// Storage key for the reentrancy guard address: `blake3("factory.reentrancy")`.
fn k_reentrancy() -> [u8; 32] {
    crypto::blake3(b"factory.reentrancy")
}

/// Storage key for `feeTo`: `blake3("factory.fee_to")`.
fn k_fee_to() -> [u8; 32] {
    crypto::blake3(b"factory.fee_to")
}

/// Storage key for `feeToSetter`: `blake3("factory.fee_to_setter")`.
fn k_fee_setter() -> [u8; 32] {
    crypto::blake3(b"factory.fee_to_setter")
}

/// Storage key for the factory's own address: `blake3("factory.self")`.
///
/// Stored at init time (128B form). Required by `createPair` to pre-compute
/// the pair address per chain spec §7.7 before calling `host.deploy`.
fn k_self() -> [u8; 32] {
    crypto::blake3(b"factory.self")
}

/// Storage key for the total number of pairs: `blake3("factory.all_pairs.len")`.
fn k_pairs_count() -> [u8; 32] {
    crypto::blake3(b"factory.all_pairs.len")
}

/// Storage key for a specific pair by token order: `blake3("factory.pair:" || t0 || t1)`.
///
/// Must be called with tokens in the canonical sorted order before lookup.
/// Also called again with tokens reversed when recording both directions.
fn k_pair(t0: &[u8; 32], t1: &[u8; 32]) -> [u8; 32] {
    // Preimage: "factory.pair:" || t0 (32B) || t1 (32B)
    let mut buf = Vec::with_capacity(13 + 32 + 32);
    buf.extend_from_slice(b"factory.pair:");
    buf.extend_from_slice(t0);
    buf.extend_from_slice(t1);
    crypto::blake3(&buf)
}

/// Storage key for the i-th entry in allPairs: `blake3("factory.all_pairs:" || u64_be(i))`.
fn k_all_pairs(i: u64) -> [u8; 32] {
    // Preimage: "factory.all_pairs:" || i as u64 big-endian (8 bytes)
    let mut buf = Vec::with_capacity(18 + 8);
    buf.extend_from_slice(b"factory.all_pairs:");
    buf.extend_from_slice(&i.to_be_bytes());
    crypto::blake3(&buf)
}

// ---------------------------------------------------------------------------
// Storage helpers
// ---------------------------------------------------------------------------

/// Read a 32-byte value from storage; returns all-zeros if the slot is unset.
fn sload(key: &[u8; 32]) -> [u8; 32] {
    state::read(key).unwrap_or([0u8; 32])
}

/// Write a 32-byte address into storage.
fn sstore(key: &[u8; 32], value: &[u8; 32]) {
    state::write(key, value);
}

/// Read a u64 from storage (stored in the low 8 bytes of a 32-byte slot,
/// big-endian, high 24 bytes are zero).
fn sload_u64(key: &[u8; 32]) -> u64 {
    let slot = sload(key);
    // Low 8 bytes of the 32-byte slot, big-endian.
    u64::from_be_bytes(slot[24..32].try_into().unwrap_or([0u8; 8]))
}

/// Write a u64 into storage (stored in the low 8 bytes of a 32-byte slot,
/// big-endian, high 24 bytes are zero).
fn sstore_u64(key: &[u8; 32], v: u64) {
    let mut slot = [0u8; 32];
    slot[24..32].copy_from_slice(&v.to_be_bytes());
    state::write(key, &slot);
}

// ---------------------------------------------------------------------------
// Pair sort helper
// ---------------------------------------------------------------------------

/// Sort two 32-byte addresses lexicographically.
///
/// Returns `(smaller, larger)` where `smaller ≤ larger` byte-wise.
/// Used everywhere a canonical `(token0, token1)` pair is needed.
pub fn sort_tokens(a: &[u8; 32], b: &[u8; 32]) -> ([u8; 32], [u8; 32]) {
    if a <= b {
        (*a, *b)
    } else {
        (*b, *a)
    }
}

/// Compute the CREATE2-style pair salt per DEX spec §5.1:
/// `blake3("dex.pair.salt:" || t0 || t1)`.
///
/// `t0` and `t1` must already be sorted (t0 ≤ t1 lexicographically).
///
/// This is `pub` so host-side integration tests can pre-compute expected
/// pair addresses.
pub fn pair_salt(t0: &[u8; 32], t1: &[u8; 32]) -> [u8; 32] {
    let mut buf = Vec::with_capacity(14 + 32 + 32);
    buf.extend_from_slice(b"dex.pair.salt:");
    buf.extend_from_slice(t0);
    buf.extend_from_slice(t1);
    crypto::blake3(&buf)
}

// ---------------------------------------------------------------------------
// Pair address pre-computation (chain spec §7.7)
// ---------------------------------------------------------------------------

/// Pre-compute the pair address that `host.deploy` will assign, using the
/// chain spec §7.7 formula:
///
/// ```text
/// pair_address = blake3("bloom-chain.v0.addr:deploy:" || deployer || ":" || salt || ":" || petal_hash)
/// ```
///
/// `deployer` is the factory's own address (stored in K_SELF at init).
///
/// This must be called BEFORE `host.deploy` so the address can be passed to
/// the pair's 128B init calldata. After `host.deploy` returns, the returned
/// address is verified to equal the pre-computed one in tests.
pub fn compute_pair_address(
    factory_addr: &[u8; 32],
    salt: &[u8; 32],
    pair_petal_hash: &[u8; 32],
) -> [u8; 32] {
    // Preimage: "bloom-chain.v0.addr:deploy:" || factory (32B) || ":" || salt (32B) || ":" || pair_petal_hash (32B)
    let prefix = b"bloom-chain.v0.addr:deploy:";
    let sep = b":";
    let mut preimage = Vec::with_capacity(prefix.len() + 32 + 1 + 32 + 1 + 32);
    preimage.extend_from_slice(prefix);
    preimage.extend_from_slice(factory_addr);
    preimage.extend_from_slice(sep);
    preimage.extend_from_slice(salt);
    preimage.extend_from_slice(sep);
    preimage.extend_from_slice(pair_petal_hash);
    crypto::blake3(&preimage)
}

