    #[test]
    fn pair_salt_order_invariance_via_sort() {
        // Given tokens a and b (unsorted), sort_tokens then pair_salt
        // must produce the same result regardless of input order.
        let mut a = [0u8; 32];
        a[31] = 100;
        let b = [0u8; 32]; // b < a

        let (t0_ab, t1_ab) = sort_tokens(&a, &b);
        let (t0_ba, t1_ba) = sort_tokens(&b, &a);

        // After sorting, both orderings produce the same (t0, t1).
        assert_eq!(t0_ab, t0_ba);
        assert_eq!(t1_ab, t1_ba);

        // And the sorted pair satisfies t0 <= t1.
        assert!(t0_ab <= t1_ab);
    }

