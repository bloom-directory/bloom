//! bloom-dex-factory — Uniswap-v2-style DEX factory petal.
//!
//! Keeps a registry of deployed pair petals and deploys new ones on demand
//! via `host.deploy` (chain spec §7.6).
//!
//! # Storage layout (DEX spec §6.3)
//!
//! All keys are 32-byte BLAKE3 digests of domain-tagged tuples (values are
//! 32-byte slots per chain spec §6.2):
//!
//! | Constant          | Preimage                                      | Value type |
//! |-------------------|-----------------------------------------------|------------|
//! | `K_PAIR_HASH`     | `blake3("factory.pair_petal_hash")`           | bytes32    |
//! | `K_REENTRANCY`    | `blake3("factory.reentrancy")`                | Address    |
//! | `K_FEE_TO`        | `blake3("factory.fee_to")`                    | Address    |
//! | `K_FEE_SETTER`    | `blake3("factory.fee_to_setter")`             | Address    |
//! | `K_SELF`          | `blake3("factory.self")`                      | Address    |
//! | `K_PAIRS_COUNT`   | `blake3("factory.all_pairs.len")`             | u64 BE     |
//! | `K_PAIR(t0, t1)`  | `blake3("factory.pair:" \|\| t0 \|\| t1)`     | Address    |
//! | `K_ALL_PAIRS(i)`  | `blake3("factory.all_pairs:" \|\| u64_be(i))` | Address    |
//!
//! `K_PAIR` is stored for **both** orderings so `get_pair` is order-invariant.
//!
//! # Selectors
//!
//! Public selectors come from `bloom-dex-abi::selectors` (generated by
//! bloom-dex-abi's build.rs from the canonical method strings in DEX spec §4.1):
//! - `FACTORY_CREATE_PAIR`      — `factory.create_pair(address,address)`
//! - `FACTORY_GET_PAIR`         — `factory.get_pair(address,address)`
//! - `FACTORY_ALL_PAIRS`        — `factory.all_pairs(u64)`
//! - `FACTORY_ALL_PAIRS_LENGTH` — `factory.all_pairs_length()`
//!
//! Factory-internal selectors come from this crate's build.rs:
//! - `SEL_FEE_TO`             — `factory.fee_to()`
//! - `SEL_FEE_TO_SETTER`      — `factory.fee_to_setter()`
//! - `SEL_SET_FEE_TO`         — `factory.set_fee_to(address)`
//! - `SEL_SET_FEE_TO_SETTER`  — `factory.set_fee_to_setter(address)`
//!
//! # init calldata
//!
//! `pair_petal_hash (32B) || reentrancy_addr (32B) || fee_to_setter (32B) || factory_self_addr (32B)` — 128 B.
//!
//! `pair_petal_hash` is the BLAKE3 hash of the `bloom-dex-pair` WASM module
//! (computed off-chain at deploy-suite time and passed in).
//! `reentrancy_addr` is the address of the deployed `bloom-dex-reentrancy`
//! instance; every pair's `init` calldata embeds it.
//! `fee_to_setter` is the initial admin address.
//! `factory_self_addr` is the factory's own pre-computed CREATE2 address; the
//! factory stores it in `K_SELF` so that `createPair` can pre-compute the
//! pair address using chain spec §7.7 before deploying.
//!
//! # Pair salt (DEX spec §5.1)
//!
//! `salt = blake3("dex.pair.salt:" || t0 || t1)`
//! where `(t0, t1)` are sorted lexicographically (byte-wise, t0 ≤ t1).
//!
//! # Pair address derivation (chain spec §7.7)
//!
//! `pair_address = blake3("bloom-chain.v0.addr:deploy:" || factory || ":" || salt || ":" || pair_petal_hash)`
//! The deployer-of-record for `host.deploy` is the factory's own address
//! (chain spec §7.7). Clients can pre-compute `pair_address` from
//! `(factory_addr, tokenA, tokenB, pair_petal_hash)` alone.
//!
//! The factory pre-computes `pair_address` before calling `host.deploy` so it
//! can pass the address to the pair's 128B init calldata (Mismatch 3 fix).

