const ZERO_ADDR: [u8; 32] = [0u8; 32];

// ---------------------------------------------------------------------------
// petal entry points
// ---------------------------------------------------------------------------

bloom_petal_sdk::petal! {
    init => do_init,
    call => do_call,
}

/// `init(pair_petal_hash (32B) || reentrancy_addr (32B) || fee_to_setter (32B) || factory_self_addr (32B))`
///
/// Stores the factory's four configuration values and initialises
/// `pairs_count = 0`. `feeTo` is set to the zero address (v0: no protocol fee).
///
/// The 128-byte layout is mandatory (DEX spec §6.3). The `factory_self_addr`
/// field is required so that `createPair` can pre-compute the pair address via
/// chain spec §7.7 before invoking `host.deploy`.
fn do_init(calldata: alloc::vec::Vec<u8>) {
    if calldata.len() < 128 {
        petal::revert("factory: init: calldata must be 128 bytes");
    }

    let pair_hash: [u8; 32] = calldata[0..32].try_into().unwrap();
    let reentrancy_addr: [u8; 32] = calldata[32..64].try_into().unwrap();
    let fee_to_setter: [u8; 32] = calldata[64..96].try_into().unwrap();
    let factory_self_addr: [u8; 32] = calldata[96..128].try_into().unwrap();

    // Store pair petal hash.
    sstore(&k_pair_hash(), &pair_hash);
    // Store reentrancy guard address.
    sstore(&k_reentrancy(), &reentrancy_addr);
    // feeTo starts at zero (v0: fee accrual deferred, spec §2 non-goals).
    sstore(&k_fee_to(), &ZERO_ADDR);
    // Store fee_to_setter.
    sstore(&k_fee_setter(), &fee_to_setter);
    // Store factory's own address for pair-address pre-computation.
    sstore(&k_self(), &factory_self_addr);
    // Initialise pairs count to zero.
    sstore_u64(&k_pairs_count(), 0);
}

/// `call(calldata_ptr, calldata_len) -> i32` — 4-byte selector dispatch.
fn do_call(calldata: alloc::vec::Vec<u8>) -> i32 {
    if calldata.len() < 4 {
        petal::revert("factory: calldata too short");
    }

    let sel: [u8; 4] = calldata[0..4].try_into().unwrap();
    let args = &calldata[4..];

    if sel == selectors::FACTORY_GET_PAIR {
        handle_get_pair(args);
    } else if sel == selectors::FACTORY_ALL_PAIRS {
        handle_all_pairs(args);
    } else if sel == selectors::FACTORY_ALL_PAIRS_LENGTH {
        handle_all_pairs_length(args);
    } else if sel == selectors::FACTORY_CREATE_PAIR {
        handle_create_pair(args);
    } else if sel == SEL_FEE_TO {
        handle_fee_to(args);
    } else if sel == SEL_FEE_TO_SETTER {
        handle_fee_to_setter(args);
    } else if sel == SEL_SET_FEE_TO {
        handle_set_fee_to(args);
    } else if sel == SEL_SET_FEE_TO_SETTER {
        handle_set_fee_to_setter(args);
    } else {
        petal::revert("factory: unknown selector");
    }

    // Unreachable — all handlers call petal::return_data or petal::revert.
    0
}

