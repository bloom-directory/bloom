/// `feeTo() -> Address`
///
/// v0: always returns the stored value (initialised to 0x0 — fee accrual
/// deferred per DEX spec §2 non-goals). The slot is writable via `setFeeTo`
/// so that v1+ can activate fee collection without redeploying the factory.
fn handle_fee_to(_args: &[u8]) {
    let fee_to = sload(&k_fee_to());
    petal::return_data(&fee_to);
}

/// `feeToSetter() -> Address`
fn handle_fee_to_setter(_args: &[u8]) {
    let setter = sload(&k_fee_setter());
    petal::return_data(&setter);
}

/// `setFeeTo(addr: Address)` — only `feeToSetter` can call.
fn handle_set_fee_to(args: &[u8]) {
    let mut buf = Buf::new(args);
    let new_fee_to = match buf.read_address() {
        Ok(a) => a,
        Err(_) => petal::revert("factory: setFeeTo: bad args"),
    };

    let setter = sload(&k_fee_setter());
    let caller = msg::sender();
    if caller != setter {
        petal::revert("factory: setFeeTo: not feeToSetter");
    }

    sstore(&k_fee_to(), &new_fee_to);
    petal::return_data(&[]);
}

/// `setFeeToSetter(addr: Address)` — only `feeToSetter` can call.
fn handle_set_fee_to_setter(args: &[u8]) {
    let mut buf = Buf::new(args);
    let new_setter = match buf.read_address() {
        Ok(a) => a,
        Err(_) => petal::revert("factory: setFeeToSetter: bad args"),
    };

    let setter = sload(&k_fee_setter());
    let caller = msg::sender();
    if caller != setter {
        petal::revert("factory: setFeeToSetter: not feeToSetter");
    }

    sstore(&k_fee_setter(), &new_setter);
    petal::return_data(&[]);
}

/// `getPair(tokenA: Address, tokenB: Address) -> Address`
///
/// Order-invariant: sorts `(tokenA, tokenB)` before lookup.
/// Returns `0x0` (32 zero bytes) if no pair exists.
fn handle_get_pair(args: &[u8]) {
    let mut buf = Buf::new(args);
    let token_a = match buf.read_address() {
        Ok(a) => a,
        Err(_) => petal::revert("factory: getPair: bad args"),
    };
    let token_b = match buf.read_address() {
        Ok(a) => a,
        Err(_) => petal::revert("factory: getPair: bad args"),
    };

    let (t0, t1) = sort_tokens(&token_a, &token_b);
    let pair = sload(&k_pair(&t0, &t1));
    petal::return_data(&pair);
}

/// `allPairs(index: u64) -> Address`
fn handle_all_pairs(args: &[u8]) {
    let mut buf = Buf::new(args);
    let index = match buf.read_u64() {
        Ok(i) => i,
        Err(_) => petal::revert("factory: allPairs: bad args"),
    };

    let count = sload_u64(&k_pairs_count());
    if index >= count {
        petal::revert("factory: allPairs: index out of bounds");
    }

    let addr = sload(&k_all_pairs(index));
    petal::return_data(&addr);
}

/// `allPairsLength() -> u64`
fn handle_all_pairs_length(_args: &[u8]) {
    let count = sload_u64(&k_pairs_count());
    // Return as 8 bytes big-endian (u64 per spec §4.1 return type).
    petal::return_data(&count.to_be_bytes());
}

/// `createPair(tokenA: Address, tokenB: Address) -> Address`
///
/// Per DEX spec §5.2 (updated for 128B pair init, Mismatch 3 fix):
/// 1. Revert if `tokenA == tokenB` ("factory: identical addresses").
/// 2. Sort to `(t0, t1)` with `t0 ≤ t1` lexicographically.
/// 3. Revert if `t0 == 0x0` ("factory: zero address").
/// 4. Revert if pair already exists ("factory: pair exists").
/// 5. Compute `salt = blake3("dex.pair.salt:" || t0 || t1)`.
/// 6. Pre-compute `pair_address` via chain spec §7.7 formula using factory's
///    own address (stored in K_SELF at init time).
/// 7. Build pair init calldata: `t0 || t1 || reentrancy_addr || pair_address` (128 bytes).
/// 8. Call `host::deploy(pair_petal_hash, salt, init_calldata)`.
///    Revert with "factory: deploy failed" on error.
/// 9. Store pair in both directions + append to `allPairs` list.
/// 10. Emit `PairCreated(t0, t1, pair_addr, allPairsLength)`.
/// 11. Return `pair_addr` (32 bytes).
fn handle_create_pair(args: &[u8]) {
    let mut buf = Buf::new(args);
    let token_a = match buf.read_address() {
        Ok(a) => a,
        Err(_) => petal::revert("factory: createPair: bad args"),
    };
    let token_b = match buf.read_address() {
        Ok(a) => a,
        Err(_) => petal::revert("factory: createPair: bad args"),
    };

    // 1. Identical addresses check.
    if token_a == token_b {
        petal::revert("factory: identical addresses");
    }

    // 2. Sort tokens lexicographically.
    let (t0, t1) = sort_tokens(&token_a, &token_b);

    // 3. Zero address check (t0 is the smaller; if t0 == 0 the other is also
    //    at risk, but identical-address check above covers t0==t1==0).
    if t0 == ZERO_ADDR {
        petal::revert("factory: zero address");
    }

    // 4. Pair-exists check.
    let existing = sload(&k_pair(&t0, &t1));
    if existing != ZERO_ADDR {
        petal::revert("factory: pair exists");
    }

    // 5. Compute salt.
    let salt = pair_salt(&t0, &t1);

    // 6. Load configuration and pre-compute pair address.
    let pair_hash = sload(&k_pair_hash());
    let reentrancy_addr = sload(&k_reentrancy());
    let factory_self = sload(&k_self());

    // Pre-compute pair address per chain spec §7.7:
    // pair_address = blake3("bloom-chain.v0.addr:deploy:" || factory || ":" || salt || ":" || pair_petal_hash)
    let precomputed_pair_addr = compute_pair_address(&factory_self, &salt, &pair_hash);

    // 7. Build pair init calldata: token0 (32B) || token1 (32B) || reentrancy_addr (32B) || pair_address (32B).
    let mut init_calldata = Vec::with_capacity(128);
    init_calldata.extend_from_slice(&t0);
    init_calldata.extend_from_slice(&t1);
    init_calldata.extend_from_slice(&reentrancy_addr);
    init_calldata.extend_from_slice(&precomputed_pair_addr);

    // 8. Deploy the pair petal via host.deploy.
    let pair_addr = match host::deploy(&pair_hash, &salt, &init_calldata) {
        Ok(addr) => addr,
        Err(_) => petal::revert("factory: deploy failed"),
    };

    // 9. Store pair in both directions.
    sstore(&k_pair(&t0, &t1), &pair_addr);
    sstore(&k_pair(&t1, &t0), &pair_addr);

    // Append to allPairs list and increment count.
    let count = sload_u64(&k_pairs_count());
    sstore(&k_all_pairs(count), &pair_addr);
    let new_count = count + 1;
    sstore_u64(&k_pairs_count(), new_count);

    // 10. Emit PairCreated(t0, t1, pair_addr, allPairsLength).
    //    Topic: FACTORY_PAIR_CREATED_EVENT (4-byte BLAKE3 prefix of
    //    "PairCreated(address,address,address,u64)", zero-padded to 32B by log::emit).
    //    Data: token0 (32B) || token1 (32B) || pair_addr (32B) || count as u64 (8B).
    let data = bloom_dex_abi::events::pack_pair_created(&t0, &t1, &pair_addr, new_count);
    log::emit(&[bloom_dex_abi::events::FACTORY_PAIR_CREATED_EVENT], &data);

    // 11. Return pair_addr.
    petal::return_data(&pair_addr);
}

