//! bloom-dex-factory — Uniswap-v2-style DEX factory petal.
//!
//! Keeps a registry of deployed pair petals and deploys new ones on demand
//! via `host.deploy` (chain spec §7.6).
//!
//! # Storage layout (declared via `storage { ... }` in `contract!` below)
//!
//! | Field              | Domain tag                                  | Value type     |
//! |--------------------|---------------------------------------------|----------------|
//! | `pair_petal_hash`  | `"factory.pair_petal_hash"`                 | bytes32        |
//! | `fee_to`           | `"factory.fee_to"`                          | Address        |
//! | `fee_to_setter`    | `"factory.fee_to_setter"`                   | Address        |
//! | `self_addr`        | `"factory.self"`     (explicit override)    | Address        |
//! | `all_pairs_len`    | `"factory.all_pairs.len"` (explicit override) | u64 BE       |
//! | `pair_of`          | `"factory.pair:" || t0 || t1`               | Address        |
//! | `all_pairs_at`     | `"factory.all_pairs:" || u64_be(i)`         | Address (raw)  |
//!
//! `pair_of` is stored for **both** orderings so `get_pair` is order-invariant.
//!
//! The `all_pairs_at` mapping uses an 8-byte big-endian `u64` index in its key
//! preimage. The chain-ABI macro's `Mapping<K, V>` DSL only accepts
//! `Address` / `U256` mapping keys in v0, so this single slot is derived via
//! a direct `bloom_chain_abi::storage::slot_mapping` call (the same helper the
//! macro itself uses) to preserve the existing on-disk key bytes.
//!
//! # ABI
//!
//! Selectors, calldata encoding, return packing, the init layout, storage
//! accessors, and event emitters are all generated by the chain-owned
//! `bloom_chain_abi::contract!` macro below. Method signatures (canonical
//! strings used for selector hashing) match the DEX v0 spec §4.1.

#![no_std]

extern crate alloc;

use alloc::vec::Vec;

use bloom_chain_abi::{DispatchError, contract, storage::slot_mapping};
use bloom_petal_sdk::{crypto, host, msg, petal};

// ---------------------------------------------------------------------------
// Chain-owned ABI declaration
// ---------------------------------------------------------------------------

contract! {
    contract Factory {
        storage {
            pair_petal_hash: Hash32;
            fee_to:          Address;
            fee_to_setter:   Address;
            self_addr:       Address @ "factory.self";
            all_pairs_len:   u64     @ "factory.all_pairs.len";

            pair_of: Mapping<(Address, Address), Address> @ "factory.pair:";
        }

        event PairCreated(
            #[indexed] token0: Address,
            #[indexed] token1: Address,
            pair: Address,
            all_pairs_length: u64,
        );

        init(pair_petal_hash: Hash32, fee_to_setter: Address, factory_self_addr: Address);

        fn create_pair(token_a: Address, token_b: Address) -> Address;
        fn get_pair(token_a: Address, token_b: Address) -> Address;
        fn all_pairs(index: u64) -> Address;
        fn all_pairs_length() -> u64;
        fn fee_to() -> Address;
        fn fee_to_setter() -> Address;
        fn set_fee_to(addr: Address);
        fn set_fee_to_setter(addr: Address);
    }
}

// ---------------------------------------------------------------------------
// Storage helpers for the u64-keyed `all_pairs_at` slot.
//
// The macro DSL does not accept `Mapping<u64, V>` in v0 (spec §A: keys are
// limited to {Address, U256, (Address, Address), (Address, U256)}). The pair
// registry's `index → pair_addr` lookup uses an 8-byte big-endian `u64` index
// as the mapping-key preimage, so we derive the slot via the same
// `bloom_chain_abi::storage::slot_mapping` helper the macro itself invokes.
// ---------------------------------------------------------------------------

const ALL_PAIRS_AT_TAG: &str = "factory.all_pairs:";

fn all_pairs_at_slot(i: u64) -> [u8; 32] {
    slot_mapping(ALL_PAIRS_AT_TAG, &i.to_be_bytes())
}

fn read_all_pairs_at(i: u64) -> [u8; 32] {
    bloom_petal_sdk::state::read(&all_pairs_at_slot(i)).unwrap_or([0u8; 32])
}

fn write_all_pairs_at(i: u64, addr: &[u8; 32]) {
    bloom_petal_sdk::state::write(&all_pairs_at_slot(i), addr);
}

// ---------------------------------------------------------------------------
// Pair sort + derivation helpers (pub for off-chain test pre-computation)
// ---------------------------------------------------------------------------

/// Sort two 32-byte addresses lexicographically; returns `(smaller, larger)`.
pub fn sort_tokens(a: &[u8; 32], b: &[u8; 32]) -> ([u8; 32], [u8; 32]) {
    if a <= b { (*a, *b) } else { (*b, *a) }
}

/// `salt = blake3("dex.pair.salt:" || t0 || t1)`. `t0` and `t1` must be sorted.
pub fn pair_salt(t0: &[u8; 32], t1: &[u8; 32]) -> [u8; 32] {
    let mut buf = Vec::with_capacity(14 + 32 + 32);
    buf.extend_from_slice(b"dex.pair.salt:");
    buf.extend_from_slice(t0);
    buf.extend_from_slice(t1);
    crypto::blake3(&buf)
}

/// Pre-compute the pair address via chain spec §7.7.
pub fn compute_pair_address(
    factory_addr: &[u8; 32],
    salt: &[u8; 32],
    pair_petal_hash: &[u8; 32],
) -> [u8; 32] {
    let prefix = b"bloom-chain.v0.addr:deploy:";
    let sep = b":";
    let mut preimage = Vec::with_capacity(prefix.len() + 32 + 1 + 32 + 1 + 32);
    preimage.extend_from_slice(prefix);
    preimage.extend_from_slice(factory_addr);
    preimage.extend_from_slice(sep);
    preimage.extend_from_slice(salt);
    preimage.extend_from_slice(sep);
    preimage.extend_from_slice(pair_petal_hash);
    crypto::blake3(&preimage)
}

const ZERO_ADDR: [u8; 32] = [0u8; 32];

// ---------------------------------------------------------------------------
// petal entry points (init + call wired into the macro-generated codec)
// ---------------------------------------------------------------------------

bloom_petal_sdk::petal! {
    init => do_init,
    call => do_call,
}

/// Decodes the 96-byte factory init payload via the chain-ABI codec and writes
/// the config slots. Strict decoding (any length other than 96 is rejected by
/// `factory::parse_init`).
///
/// Phase C: the legacy `reentrancy_addr` field has been removed from both the
/// pair's init payload and the factory's own init payload, since the
/// reentrancy guard moved into `#[nonreentrant]` (no separate reentrancy
/// petal). The factory init shrinks from 128 → 96 bytes.
fn do_init(calldata: alloc::vec::Vec<u8>) {
    let args = match factory::parse_init(&calldata) {
        Ok(a) => a,
        Err(_) => petal::revert("factory: init: calldata must be 96 bytes"),
    };

    factory::abi::storage::set_pair_petal_hash(&args.pair_petal_hash);
    factory::abi::storage::set_fee_to(&ZERO_ADDR);
    factory::abi::storage::set_fee_to_setter(&args.fee_to_setter);
    factory::abi::storage::set_self_addr(&args.factory_self_addr);
    factory::abi::storage::set_all_pairs_len(0);
}

/// Routes a method call through the macro-generated dispatcher and translates
/// the typed result into the petal-SDK return / revert ABI.
fn do_call(calldata: alloc::vec::Vec<u8>) -> i32 {
    let mut handler = FactoryHandler;
    let caller = msg::sender();
    match factory::dispatch(&mut handler, &caller, &calldata) {
        Ok(data) => petal::return_data(&data),
        Err(DispatchError::ShortCalldata) => petal::revert("factory: calldata too short"),
        Err(DispatchError::UnknownSelector(_)) => petal::revert("factory: unknown selector"),
        Err(DispatchError::Decode(_)) => petal::revert("factory: bad args"),
        Err(DispatchError::Unauthorized) => petal::revert("factory: unauthorized"),
        Err(DispatchError::Handler(msg)) => petal::revert(msg),
    }
}

// ---------------------------------------------------------------------------
// Handler — pure business logic against the chain-owned ABI shape
// ---------------------------------------------------------------------------

struct FactoryHandler;

impl factory::Handler for FactoryHandler {
    fn create_pair(
        &mut self,
        token_a: [u8; 32],
        token_b: [u8; 32],
    ) -> Result<[u8; 32], &'static str> {
        if token_a == token_b {
            return Err("factory: identical addresses");
        }

        let (t0, t1) = sort_tokens(&token_a, &token_b);
        if t0 == ZERO_ADDR {
            return Err("factory: zero address");
        }

        if factory::abi::storage::pair_of::get((&t0, &t1)) != ZERO_ADDR {
            return Err("factory: pair exists");
        }

        let salt = pair_salt(&t0, &t1);
        let pair_hash = factory::abi::storage::pair_petal_hash();
        let factory_self = factory::abi::storage::self_addr();
        let precomputed_pair_addr = compute_pair_address(&factory_self, &salt, &pair_hash);

        // Pair init: t0 || t1 || pair_self_addr (96 bytes).
        //
        // The pair's init payload is a raw `host.deploy` blob (not a
        // selector-dispatched method call), so we build it inline rather than
        // pulling in `bloom-dex-pair` as an rlib dep just to call
        // `pair::init_calldata`. The format is byte-identical to that helper
        // and is asserted in the `pair_init_payload_is_exactly_96_bytes` test
        // below.
        //
        // The pre-Phase-B layout included a `reentrancy_addr` field; that field
        // was dropped when the pair's reentrancy guard moved into the language
        // via `#[nonreentrant]`. Phase C removes the matching `reentrancy_addr`
        // slot from the factory's own state and `init(...)` signature.
        let mut init_calldata = Vec::with_capacity(96);
        init_calldata.extend_from_slice(&t0);
        init_calldata.extend_from_slice(&t1);
        init_calldata.extend_from_slice(&precomputed_pair_addr);

        let pair_addr = host::deploy(&pair_hash, &salt, &init_calldata)
            .map_err(|_| "factory: deploy failed")?;

        // Store pair in both directions; append to allPairs.
        factory::abi::storage::pair_of::set((&t0, &t1), &pair_addr);
        factory::abi::storage::pair_of::set((&t1, &t0), &pair_addr);

        let count = factory::abi::storage::all_pairs_len();
        write_all_pairs_at(count, &pair_addr);
        let new_count = count + 1;
        factory::abi::storage::set_all_pairs_len(new_count);

        // Emit PairCreated(t0, t1, pair_addr, allPairsLength).
        factory::abi::events::emit_pair_created(&t0, &t1, &pair_addr, new_count);

        Ok(pair_addr)
    }

    fn get_pair(
        &mut self,
        token_a: [u8; 32],
        token_b: [u8; 32],
    ) -> Result<[u8; 32], &'static str> {
        let (t0, t1) = sort_tokens(&token_a, &token_b);
        Ok(factory::abi::storage::pair_of::get((&t0, &t1)))
    }

    fn all_pairs(&mut self, index: u64) -> Result<[u8; 32], &'static str> {
        let count = factory::abi::storage::all_pairs_len();
        if index >= count {
            return Err("factory: allPairs: index out of bounds");
        }
        Ok(read_all_pairs_at(index))
    }

    fn all_pairs_length(&mut self) -> Result<u64, &'static str> {
        Ok(factory::abi::storage::all_pairs_len())
    }

    fn fee_to(&mut self) -> Result<[u8; 32], &'static str> {
        Ok(factory::abi::storage::fee_to())
    }

    fn fee_to_setter(&mut self) -> Result<[u8; 32], &'static str> {
        Ok(factory::abi::storage::fee_to_setter())
    }

    fn set_fee_to(&mut self, addr: [u8; 32]) -> Result<(), &'static str> {
        let setter = factory::abi::storage::fee_to_setter();
        if msg::sender() != setter {
            return Err("factory: setFeeTo: not feeToSetter");
        }
        factory::abi::storage::set_fee_to(&addr);
        Ok(())
    }

    fn set_fee_to_setter(&mut self, addr: [u8; 32]) -> Result<(), &'static str> {
        let setter = factory::abi::storage::fee_to_setter();
        if msg::sender() != setter {
            return Err("factory: setFeeToSetter: not feeToSetter");
        }
        factory::abi::storage::set_fee_to_setter(&addr);
        Ok(())
    }
}

