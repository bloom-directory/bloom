#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sort_tokens_already_sorted() {
        let a = [0u8; 32];
        let mut b = [0u8; 32];
        b[31] = 1;
        let (t0, t1) = sort_tokens(&a, &b);
        assert_eq!(t0, a);
        assert_eq!(t1, b);
    }

    #[test]
    fn sort_tokens_reversed() {
        let mut a = [0u8; 32];
        a[31] = 5;
        let b = [0u8; 32];
        let (t0, t1) = sort_tokens(&a, &b);
        assert_eq!(t0, b);
        assert_eq!(t1, a);
    }

    #[test]
    fn sort_tokens_is_commutative() {
        let mut a = [0u8; 32];
        a[0] = 0x10;
        let mut b = [0u8; 32];
        b[0] = 0x20;
        let (t0_ab, t1_ab) = sort_tokens(&a, &b);
        let (t0_ba, t1_ba) = sort_tokens(&b, &a);
        assert_eq!(t0_ab, t0_ba);
        assert_eq!(t1_ab, t1_ba);
    }

    // ---- Selector parity tests ----

    #[test]
    fn factory_selectors_match_dex_v0_canonical_strings() {
        fn _expected(method: &[u8]) -> [u8; 4] {
            let h = blake3::hash(method);
            let b = h.as_bytes();
            [b[0], b[1], b[2], b[3]]
        }
        assert_eq!(factory::SEL_CREATE_PAIR,        _expected(b"factory.create_pair(address,address)"));
        assert_eq!(factory::SEL_GET_PAIR,           _expected(b"factory.get_pair(address,address)"));
        assert_eq!(factory::SEL_ALL_PAIRS,          _expected(b"factory.all_pairs(u64)"));
        assert_eq!(factory::SEL_ALL_PAIRS_LENGTH,   _expected(b"factory.all_pairs_length()"));
        assert_eq!(factory::SEL_FEE_TO,             _expected(b"factory.fee_to()"));
        assert_eq!(factory::SEL_FEE_TO_SETTER,      _expected(b"factory.fee_to_setter()"));
        assert_eq!(factory::SEL_SET_FEE_TO,         _expected(b"factory.set_fee_to(address)"));
        assert_eq!(factory::SEL_SET_FEE_TO_SETTER,  _expected(b"factory.set_fee_to_setter(address)"));
    }

    // ---- Event topic parity (canonical-string assertion) ----

    #[test]
    fn event_topic_matches_canonical_signature() {
        // The chain-ABI macro builds the event signature as
        // `"<EventName>(<type1>,<type2>,...)"` (no contract-domain prefix —
        // see `event_sig` in bloom-chain-abi-macros). The `PairCreated`
        // declaration above is:
        //   event PairCreated(
        //       #[indexed] token0: Address,
        //       #[indexed] token1: Address,
        //       pair: Address,
        //       all_pairs_length: u64,
        //   );
        // so the canonical signature is the string below.
        let exp = blake3::hash(b"PairCreated(address,address,address,u64)");
        let b = exp.as_bytes();
        assert_eq!(factory::abi::events::PAIR_CREATED_TOPIC, [b[0], b[1], b[2], b[3]]);
    }

    // ---- Storage slot byte-equality parity (pre- vs post-migration) ----
    //
    // The macro-generated storage accessors derive slot keys from the
    // declared field tags. These asserts lock the storage layout: a slot tag
    // rename in the `contract!` block would change the on-disk key and break
    // upgrade compatibility. We compare against blake3 of the explicit byte
    // string the pre-migration factory used.

    #[test]
    fn storage_slot_parity_scalars() {
        use bloom_chain_abi::storage::slot_scalar;

        // Pre-migration tags used by the hand-rolled `k_*` helpers.
        let exp = blake3::hash(b"factory.pair_petal_hash");
        assert_eq!(&slot_scalar("factory.pair_petal_hash")[..], &exp.as_bytes()[..]);

        let exp = blake3::hash(b"factory.fee_to");
        assert_eq!(&slot_scalar("factory.fee_to")[..], &exp.as_bytes()[..]);

        let exp = blake3::hash(b"factory.fee_to_setter");
        assert_eq!(&slot_scalar("factory.fee_to_setter")[..], &exp.as_bytes()[..]);

        // `self_addr` uses an explicit `@ "factory.self"` override.
        let exp = blake3::hash(b"factory.self");
        assert_eq!(&slot_scalar("factory.self")[..], &exp.as_bytes()[..]);

        // `all_pairs_len` uses an explicit `@ "factory.all_pairs.len"` override
        // so the on-disk slot byte-matches the pre-migration `k_pairs_count`.
        let exp = blake3::hash(b"factory.all_pairs.len");
        assert_eq!(&slot_scalar("factory.all_pairs.len")[..], &exp.as_bytes()[..]);
    }

    #[test]
    fn storage_slot_parity_pair_of_mapping() {
        use bloom_chain_abi::storage::slot_mapping;

        let t0 = [0x11u8; 32];
        let t1 = [0x22u8; 32];

        // Pre-migration: blake3("factory.pair:" || t0 || t1).
        let mut buf = Vec::<u8>::new();
        buf.extend_from_slice(b"factory.pair:");
        buf.extend_from_slice(&t0);
        buf.extend_from_slice(&t1);
        let exp = blake3::hash(&buf);

        // Macro mapping encodes (Address, Address) as the 64-byte concat.
        let mut concat = [0u8; 64];
        concat[..32].copy_from_slice(&t0);
        concat[32..].copy_from_slice(&t1);
        assert_eq!(
            &slot_mapping("factory.pair:", &concat)[..],
            &exp.as_bytes()[..]
        );
    }

    #[test]
    fn storage_slot_parity_all_pairs_mapping() {
        use bloom_chain_abi::storage::slot_mapping;

        let i: u64 = 0xdead_beef;

        // Pre-migration: blake3("factory.all_pairs:" || u64_be(i)).
        let mut buf = Vec::<u8>::new();
        buf.extend_from_slice(b"factory.all_pairs:");
        buf.extend_from_slice(&i.to_be_bytes());
        let exp = blake3::hash(&buf);

        assert_eq!(
            &slot_mapping("factory.all_pairs:", &i.to_be_bytes())[..],
            &exp.as_bytes()[..]
        );

        // The local `all_pairs_at_slot(i)` helper must produce the same bytes
        // (this is the production code path).
        assert_eq!(&all_pairs_at_slot(i)[..], &exp.as_bytes()[..]);
    }

    // ---- Init payload tests ----

    #[test]
    fn init_payload_is_exactly_96_bytes() {
        let pair_hash    = [0x01u8; 32];
        let fee_setter   = [0x03u8; 32];
        let factory_self = [0x04u8; 32];

        let payload = factory::init_calldata(&pair_hash, &fee_setter, &factory_self);
        assert_eq!(payload.len(), 96, "factory init must be 96 bytes");
        assert_eq!(&payload[0..32],  &pair_hash);
        assert_eq!(&payload[32..64], &fee_setter);
        assert_eq!(&payload[64..96], &factory_self);

        let parsed = factory::parse_init(&payload).unwrap();
        assert_eq!(parsed.pair_petal_hash, pair_hash);
        assert_eq!(parsed.fee_to_setter, fee_setter);
        assert_eq!(parsed.factory_self_addr, factory_self);
    }

    #[test]
    fn init_payload_rejects_wrong_length() {
        // 95 bytes is short by one — must error.
        let bad = [0u8; 95];
        assert!(factory::parse_init(&bad).is_err());
        // 97 bytes is long by one — strict decoding rejects trailing bytes.
        let bad = [0u8; 97];
        assert!(factory::parse_init(&bad).is_err());
        // The pre-Phase-C 128-byte payload must also be rejected.
        let bad = [0u8; 128];
        assert!(factory::parse_init(&bad).is_err());
    }

    // ---- Pair init payload constructed for `host.deploy` ----

    #[test]
    fn pair_init_payload_is_exactly_96_bytes() {
        // The factory's `create_pair` builds the pair init payload inline
        // (it's a raw `host.deploy` blob, not a selector-dispatched method).
        // Phase C dropped the `reentrancy_addr` field, so the payload is
        // exactly `t0 || t1 || pair_self_addr` — 96 bytes. This test mirrors
        // the production layout to lock the wire format against accidental
        // size drift.
        let t0 = [0xAAu8; 32];
        let t1 = [0xBBu8; 32];
        let pair_self = [0xCCu8; 32];
        let mut cd = Vec::<u8>::with_capacity(96);
        cd.extend_from_slice(&t0);
        cd.extend_from_slice(&t1);
        cd.extend_from_slice(&pair_self);
        assert_eq!(cd.len(), 96, "pair init must be 96 bytes");
        assert_eq!(&cd[0..32],   &t0);
        assert_eq!(&cd[32..64],  &t1);
        assert_eq!(&cd[64..96],  &pair_self);
    }

    #[test]
    fn create_pair_call_layout() {
        // Client-side call builder produces selector + two addresses = 4 + 64.
        let a = [0xAAu8; 32];
        let b = [0xBBu8; 32];
        let cd = factory::calls::create_pair(&a, &b);
        assert_eq!(cd.len(), 4 + 32 + 32);
        assert_eq!(&cd[0..4], &factory::SEL_CREATE_PAIR);
        assert_eq!(&cd[4..36], &a);
        assert_eq!(&cd[36..68], &b);
    }
}
